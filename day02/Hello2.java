public class Hello2 {
    public static void main(String a[])
    {
        //binary numbers
        int n1=0b1010;
        //hexadecimal numbers
        int n2=0x7E;
        //number of zeros easy to read
        int n3=10_00_00_000;
        System.out.println(n1);
        System.out.println(n2);
        System.out.println(n3);

        //characters can be just incremented
        char b='q';
        System.out.println(b);
        b++;
        System.out.println(b);
    }
}
